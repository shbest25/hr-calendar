// 복지카드 엑셀 만들기 — 순수 함수만. 화면이 파일 바이트를 받아 내려받는다.
// ① 품의 첨부 지급내역 ② 카드사 업로드용 한도설정 ③ 재무팀 공유용 발급 및 해지내역.
// 회사 허브는 지난달 확정본 파일을 틀로 삼아 데이터 줄만 바꿔 끼우지만, 여기서는 틀 없이 같은 모양으로 새로 만든다.
// 주민번호·카드번호는 받은 그대로 파일에만 들어간다. 여기서 찍거나 오류 글에 넣지 않는다.
import { 엑셀여러시트 } from './xlsxmake.js';
import { 날짜정리, 집계, 월글 } from './welfarecalc.js';

// 'YYYY-MM-DD' → 엑셀 날짜 숫자(1900 날짜 체계). 못 읽으면 ''.
export function 엑셀날짜(iso) {
  const 날 = 날짜정리(iso);
  if (!날) return '';
  const [y, m, d] = 날.split('-').map(Number);
  return Math.round((Date.UTC(y, m - 1, d) - Date.UTC(1899, 11, 30)) / 86400000);
}

const 년월 = (ym) => [ym.slice(0, 4), Number(ym.slice(5, 7))];

// ① 품의 첨부 지급내역 — 1행 제목, 2행 머리글, 3행부터 NO·사번·이름·소속·실·부서·파트·직책·입사일·부여금액·이슈사항, 끝에 합계와 금액별 집계.
export function 지급내역만들기(rows, ym) {
  const 셈 = 집계(rows);
  const 줄들 = rows.map((r, i) => [i + 1, r.사번, r.이름, r.소속, r.실, r.부서, r.파트, r.직책, r.입사일, r.금액, r.이슈]);
  const 표 = [
    [`${월글(ym)} 복지카드 지급내역`],
    ['NO', '사번', '이름', '소속', '실', '부서', '파트', '직책', '입사일', '부여금액', '이슈사항'],
    ...줄들,
    ['합계', null, null, null, null, null, null, null, null, 셈.합계, `${셈.인원}명`],
    [],
    ['금액별 집계', '금액', '인원', '소계'],
    ...셈.금액별.map((g) => [null, g.금액, g.인원, g.소계]),
    [null, '합계', 셈.인원, 셈.합계],
  ];
  return 엑셀여러시트({ sheets: [{ name: `${년월(ym)[1]}월 지급내역`, rows: 표, headRows: 표.length, merges: ['A1:K1'] }] });
}

// ② 카드사 업로드용 한도설정 — 시트 「한도변경신청」 8행부터 한 사람 한 줄.
// 주민: 사번 → 주민등록번호. 이 앱은 주민번호를 두지 않으므로 보통 비어 있고, 그러면 칸을 비워 두고 돌려준 '없는' 사번을 화면이 알린다.
export function 한도설정만들기(rows, 주민, ym) {
  const [y, m] = 년월(ym);
  const 시작 = `${y}${String(m).padStart(2, '0')}01`;
  const 끝 = `${y}1231`;
  const 없는 = rows.filter((r) => !String(주민?.[r.사번] ?? '').trim()).map((r) => r.사번);
  const 줄들 = rows.map((r) => [r.사번, String(주민?.[r.사번] ?? '').trim(), 시작, 끝, '01', r.금액, '01', r.금액, 'A']);
  const 표 = [
    ['복지카드 한도변경 신청'],
    [`대상월: ${월글(ym)}`],
    ['사번·주민등록번호·적용 시작일·종료일·구분·금액 순입니다. 카드사 양식에 맞춰 8행부터 한 사람 한 줄입니다.'],
    [], [], [],
    ['사번', '주민등록번호', '시작일', '종료일', '구분1', '금액1(식대·생활)', '구분2', '한도액', '코드'],
    ...줄들,
  ];
  return { bytes: 엑셀여러시트({ sheets: [{ name: '한도변경신청', rows: 표, headRows: 7 }] }), 없는 };
}

// ③ 재무팀 공유용 발급 및 해지내역 — 시트 셋, 2행 머리글, 3행부터 B 열에서 시작.
const 카드머리 = ['상품명', '소지자명', '발급일자', '발급구분', '유효기한', '제휴카드ID', '소속', '실', '부서', '파트'];
const 발급해지시트 = [
  { name: '발급내역', 머리: ['순번', '카드번호', ...카드머리], 열쇠: '발급' },
  { name: '재발급 대상자 기존카드', 머리: ['순번', '기존카드번호', ...카드머리], 열쇠: '옛카드' },
  { name: '해지 리스트', 머리: ['순번', '소지자명', '카드번호', '소속', '실', '부서', '파트'], 열쇠: '해지' },
];

// 결과: 발급비교 결과. 조직: 사번 → {소속,실,부서,파트}. 못 찾으면 '-'.
export function 발급해지만들기(결과, 조직) {
  const 소속칸 = (사번) => {
    const o = 조직(사번) || {};
    return ['소속', '실', '부서', '파트'].map((k) => o[k] || '-');
  };
  const 줄들 = (열쇠) => (결과[열쇠] || []).map((c, i) => (열쇠 === '해지'
    ? [i + 1, c.소지자명, c.카드번호, ...소속칸(c.제휴카드ID)]
    : [i + 1, c.카드번호, c.상품명, c.소지자명, c.발급일자, c.발급구분, c.유효기한, c.제휴카드ID, ...소속칸(c.제휴카드ID)]));
  return 엑셀여러시트({
    sheets: 발급해지시트.map((s) => {
      const rows = [[], [null, ...s.머리], ...줄들(s.열쇠).map((줄) => [null, ...줄])];
      return { name: s.name, rows, headRows: rows.length };
    }),
  });
}

// 눌러 보기용 발급현황 파일 둘(카드사에서 받는 꼴을 흉내 낸다). 카드번호는 모두 지어낸 것이다.
// 직전: 명단 사람마다 카드 한 장. 이번: 한 명은 새로 발급, 한 명은 재발급(옛 카드가 사라지고 새 번호), 한 명은 해지.
export function 예시발급현황(rows, { 직전날, 이번날, 회사 = '우리회사' }) {
  const 번호 = (i, 꼬리) => `9411-${String(1000 + i).padStart(4, '0')}-****-${String(꼬리).padStart(4, '0')}`;
  const 유효 = (날) => `${Number(날.slice(0, 4)) + 5}-${날.slice(5, 7)}`;
  const 카드 = (r, i, 꼬리, 날) => [번호(i, 꼬리), `${회사} 복지카드`, r.이름, 날, '신규', 유효(날), r.사번];
  const 머리 = ['카드번호', '상품명', '소지자명', '발급일자', '발급구분', '유효기한', '제휴카드ID'];
  const 이전 = rows.map((r, i) => 카드(r, i, 1, 직전날));
  const 이번 = [];
  rows.forEach((r, i) => {
    if (i === rows.length - 1) return;                                   // 마지막 사람: 해지(이번 파일에 없음)
    if (i === 1) { const c = 카드(r, i, 2, 이번날); c[4] = '재발급'; 이번.push(c); return; } // 둘째 사람: 재발급(새 번호)
    이번.push(이전[i]);
  });
  if (rows.length) 이번.push([번호(99, 7), `${회사} 복지카드`, '새입사', 이번날, '신규', 유효(이번날), 'E1999']); // 새로 발급
  const 파일 = (줄들) => 엑셀여러시트({ sheets: [{ name: '발급현황', rows: [머리, ...줄들], headRows: 1 }] });
  return { 이전: 파일(이전), 이번: 파일(이번) };
}
