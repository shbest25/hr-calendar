//
// 대량 전송 엑셀의 '추가 내용' 칸(1-텍스트, 2-텍스트 …)은 계약서 템플릿의 요청자 입력란이다.
// 칸 번호는 템플릿 화면의 위치 순서(쪽 → 위에서 아래 → 왼쪽에서 오른쪽)다. 템플릿의 칸을 옮기거나 더하면 번호가 바뀌니
// 아래 정규칸·계약칸을 다시 맞춰야 한다. 여기 적힌 번호는 보기용 템플릿 기준이다.
//
// **연봉은 브라우저 밖으로 나가지 않는다** — 기록에 남기지 않는 값이라 저장소로 보내지 않고 여기서만 쓴다.
