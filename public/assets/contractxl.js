// 회사마다 다른 값. [설정]의 회사 정보에서 가져오고, 없으면 이 값을 쓴다.
export const 기본규칙 = { 식대: 200000, 소재지: '서울특별시 ○○구 ○○로 00', 문서명머리: '[우리회사] 근로 · 연봉계약서_' };

export const 월급여 = (연봉) => Math.round(Number(연봉) / 12);
export const 기본급 = (연봉, 식대 = 기본규칙.식대) => 월급여(연봉) - 식대;

const 날꼴 = /^(\d{4})-(\d{2})-(\d{2})$/;
const 말일 = (y, m) => new Date(Date.UTC(y, m, 0)).getUTCDate();   // m 은 1~12
const 두자리 = (n) => String(n).padStart(2, '0');
const 날글 = (y, m, d) => `${y}-${두자리(m)}-${두자리(d)}`;

function 날읽기(s) {
  const m = 날꼴.exec(String(s ?? '').trim());
  if (!m) return null;
  const [y, mo, d] = [Number(m[1]), Number(m[2]), Number(m[3])];
  if (mo < 1 || mo > 12 || d < 1 || d > 말일(y, mo)) return null;
  return { y, m: mo, d };
}

// 연봉계약기간 끝. 1~3분기(1~9월) 입사는 그해 12/31, 4분기 입사는 다음 해 12/31.
// 계약직은 계약 종료일을 넘지 않는다.
export function 연봉끝(입사일, 계약종료일 = '') {
  const s = 날읽기(입사일);
  const 규칙 = `${s.m >= 10 ? s.y + 1 : s.y}-12-31`;
  const 끝 = 날읽기(계약종료일) ? String(계약종료일).trim() : '';
  return 끝 && 끝 < 규칙 ? 끝 : 규칙;
}

// 수습 3개월의 마지막 날. 3개월 뒤 같은 날의 전날이고, 그런 날이 없으면 그 달 말일이다(민법 160조).
export function 수습끝(입사일) {
  const s = 날읽기(입사일);
  let y = s.y;
  let m = s.m + 3;
  if (m > 12) { m -= 12; y += 1; }
  if (s.d > 말일(y, m)) return 날글(y, m, 말일(y, m));
  const 전날 = new Date(Date.UTC(y, m - 1, s.d - 1));
  return 날글(전날.getUTCFullYear(), 전날.getUTCMonth() + 1, 전날.getUTCDate());
}

const 쉼표 = (n) => Number(n).toLocaleString('en-US');
const 조각 = (날) => { const s = 날읽기(날); return [String(s.y), 두자리(s.m), 두자리(s.d)]; };
const 한글날 = (날) => { const [y, m, d] = 조각(날); return `${y}년 ${m}월 ${d}일`; };

// 템플릿 칸 번호(1부터). 날짜는 [년, 월, 일] 칸 번호.
