const 종류 = (v) => {
  const s = String(v ?? '').trim();
  if (s === '정규' || s === '정규직') return '정규';
  if (s === '계약' || s === '계약직') return '계약';
  return '';
};

export const 종류이름 = { 정규: '정규직', 계약: '계약직' };

// 사람 한 명의 엑셀 한 줄. 모자라면 { blocked: 까닭 }.
// 돌려주는 것: { kind, 문서명, 이름, 이메일, texts } — texts[0] 이 '1-텍스트' 칸이다.
export function 계약서줄({ 고용형태, 이름, 이메일, 입사일, 연봉, 계약종료일 }, 규칙 = 기본규칙) {
  const { 식대, 소재지, 문서명머리 } = { ...기본규칙, ...(규칙 ?? {}) };
  const kind = 종류(고용형태);
  const 성명 = String(이름 ?? '').trim();
  const 메일 = String(이메일 ?? '').trim();
  const 돈 = String(연봉 ?? '').replace(/[,\s]/g, '');
  const 끝날 = String(계약종료일 ?? '').trim();
  if (!kind) return { blocked: `고용형태가 정규·계약이 아닙니다(지금: ${String(고용형태 ?? '').trim() || '비어 있음'}).` };
  if (!성명) return { blocked: '이름이 비어 있습니다.' };
  if (!메일) return { blocked: '서명 요청을 받을 메일 주소(개인이메일)가 비어 있습니다.' };
  if (!날읽기(입사일)) return { blocked: '입사일이 비었거나 날짜 꼴(YYYY-MM-DD)이 아닙니다.' };
  if (!/^\d+$/.test(돈) || Number(돈) <= 0) return { blocked: '연봉을 숫자로 적어 주세요(쉼표 없이 숫자만).' };
  if (기본급(돈, 식대) <= 0) return { blocked: `연봉이 너무 작습니다 — 월 급여가 식대(${쉼표(식대)}원)보다 작습니다.` };
  if (kind === '계약') {
    if (!날읽기(끝날)) return { blocked: '계약직은 계약 종료일이 필요합니다. 입사자 정보에 계약 종료일을 적어 주세요.' };
    if (끝날 < String(입사일).trim()) return { blocked: '계약 종료일이 입사일보다 앞입니다.' };
  }

  const 입사 = String(입사일).trim();
  const 칸 = kind === '정규' ? 정규칸 : 계약칸;
  const texts = Array(칸.수).fill('');
  const 넣기 = (번호, 값) => { texts[번호 - 1] = 값; };
  const 날넣기 = (번호들, 날) => 조각(날).forEach((v, i) => 넣기(번호들[i], v));

  for (const 번호 of 칸.성명) 넣기(번호, 성명);
  넣기(칸.소재지, 소재지);
  if (kind === '정규') {
    넣기(칸.근로시작글, `${한글날(입사)}로부터`);
  } else {
    날넣기(칸.근로시작, 입사);
    날넣기(칸.근로끝, 끝날);
  }
  날넣기(칸.연봉시작, 입사);
  날넣기(칸.연봉끝, 연봉끝(입사, kind === '계약' ? 끝날 : ''));
  넣기(칸.총연봉, `${쉼표(돈)}원`);
  넣기(칸.기본급, 쉼표(기본급(돈, 식대)));
  넣기(칸.월급여, 쉼표(월급여(돈)));
  // 계약 기간이 수습 3개월보다 짧으면 수습도 계약 종료일에 끝난다.
  const 수습 = 수습끝(입사);
  넣기(칸.수습끝, 한글날(kind === '계약' && 끝날 < 수습 ? 끝날 : 수습));
  for (const 번호들 of 칸.서명날) 날넣기(번호들, 입사);

  return { kind, 문서명: 문서명머리 + 성명, 이름: 성명, 이메일: 메일, texts, 요약: { 월급여: 월급여(돈), 기본급: 기본급(돈, 식대), 연봉끝: 연봉끝(입사, kind === '계약' ? 끝날 : ''), 수습끝: 수습 } };
}

