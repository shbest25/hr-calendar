// 계약서줄 여럿(같은 템플릿)을 대량 전송 표로. 돌려주는 것: { rows, merges } — 엑셀만들기 에 그대로 넘긴다.
export function 대량전송표(줄들) {
  const 칸수 = 줄들[0].texts.length;
  const 묶음 = Array(앞칸.length + 칸수).fill(null);
  묶음[0] = '서명자 설정';
  묶음[5] = '인증 수단 및 기타 설정';
  묶음[14] = '참조자 설정';
  묶음[16] = '추가 내용';
  const 이름줄 = [...앞칸, ...Array.from({ length: 칸수 }, (_, i) => `${i + 1}-텍스트`)];
  const 사람줄 = 줄들.map((r) => [r.문서명, r.이름, r.이메일, ...Array(앞칸.length - 3).fill(''), ...r.texts]);
  return {
    rows: [묶음, 이름줄, ...사람줄],
    merges: ['A1:E1', 'F1:N1', 'O1:P1', `Q1:${열이름(앞칸.length + 칸수)}1`],
  };
}

